import path from "node:path";

const routeFile = /^(page|layout|loading|error)\.(tsx|ts)$/;
const identifier = /^[A-Za-z_$][\w$]*$/;
const staticSegment = /^[A-Za-z0-9][A-Za-z0-9_-]*$/;

type RouteKind = "page" | "layout" | "loading" | "error";
type RouteNode = {
  folder: string;
  directory: string;
  files: Partial<Record<RouteKind, string>>;
  children: Map<string, RouteNode>;
};

export function segmentFor(folder: string): string | null {
  if (/^\([A-Za-z0-9_-]+\)$/.test(folder)) return null;
  const catchAll = /^\[\.\.\.([A-Za-z_$][\w$]*)\]$/.exec(folder);
  if (catchAll) return "*";
  const dynamic = /^\[([A-Za-z_$][\w$]*)\]$/.exec(folder);
  if (dynamic) return `:${dynamic[1]}`;
  if (staticSegment.test(folder)) return folder;
  throw new Error(`Invalid route segment: ${folder}`);
}

function createNode(folder = "", directory = ""): RouteNode {
  return { folder, directory, files: {}, children: new Map() };
}

export function buildTree(files: readonly string[]): RouteNode {
  const root = createNode();
  for (const file of [...files].sort()) {
    const normalized = file.replaceAll("\\", "/");
    const parts = normalized.split("/");
    const match = routeFile.exec(parts.pop() ?? "");
    if (!match) continue;
    let node = root;
    for (const folder of parts) {
      segmentFor(folder);
      let child = node.children.get(folder);
      if (!child) {
        child = createNode(folder, [...(node.directory ? [node.directory] : []), folder].join("/"));
        node.children.set(folder, child);
      }
      node = child;
    }
    const kind = match[1] as RouteKind;
    if (node.files[kind]) {
      throw new Error(`Duplicate ${match[1]} in ${node.directory || "root"}`);
    }
    node.files[kind] = normalized;
  }
  validateTree(root);
  return root;
}

function validateTree(root: RouteNode): void {
  const pagePaths = new Map<string, string>();
  function visit(node: RouteNode, segments: string[]): void {
    const segment = node.folder ? segmentFor(node.folder) : null;
    const next = segment ? [...segments, segment] : segments;
    if (node.files.page) {
      const matcher = `/${next.map((item) => item.startsWith(":") ? ":" : item).join("/")}`;
      const existing = pagePaths.get(matcher);
      if (existing) throw new Error(`Route collision ${matcher}: ${existing} and ${node.files.page}`);
      pagePaths.set(matcher, node.files.page);
    }
    if (segment === "*" && node.children.size) throw new Error(`Catch-all route cannot have child folders: ${node.directory}`);
    const siblings = new Set();
    for (const child of node.children.values()) {
      const childSegment = segmentFor(child.folder);
      const matcher = childSegment?.startsWith(":") ? ":" : childSegment;
      if (matcher && siblings.has(matcher)) throw new Error(`Ambiguous sibling routes in ${node.directory || "root"}: ${matcher}`);
      if (matcher) siblings.add(matcher);
      visit(child, next);
    }
  }
  visit(root, []);
  if (!pagePaths.size) throw new Error("No page.tsx routes found");
}

const quote = (value: string): string => JSON.stringify(value);

function importPath(file: string): string {
  return `../pages/${file.replace(/\.(ts|tsx)$/, "")}`;
}

function lazyModule(file: string, property: string): string {
  return `${property}: (await import(${quote(importPath(file))})).default`;
}

function routeSource(node: RouteNode, indent = 2, isRoot = false): string {
  const space = " ".repeat(indent);
  const properties: string[] = [];
  if (isRoot) properties.push('path: "/"', "HydrateFallback: BootFallback", "ErrorBoundary: GlobalRouteError");
  else {
    const segment = segmentFor(node.folder);
    if (segment) properties.push(`path: ${quote(segment)}`);
  }
  const lazyFields: string[] = [];
  if (node.files.layout) lazyFields.push(lazyModule(node.files.layout, "Component"));
  else properties.push("Component: Outlet");
  if (node.files.error) lazyFields.push(lazyModule(node.files.error, "ErrorBoundary"));
  if (node.files.loading) lazyFields.push(lazyModule(node.files.loading, "HydrateFallback"));
  if (lazyFields.length) properties.push(`lazy: async () => ({ ${lazyFields.join(", ")} })`);
  const children: string[] = [];
  if (node.files.page) {
    children.push(`${space}  { index: true, lazy: async () => ({ ${lazyModule(node.files.page, "Component")} }) }`);
  }
  for (const child of [...node.children.values()].sort((a, b) => a.folder.localeCompare(b.folder))) {
    children.push(routeSource(child, indent + 2));
  }
  if (children.length) properties.push(`children: [\n${children.join(",\n")}\n${space}]`);
  return `${space}{ ${properties.join(", ")} }`;
}

export function generateSource(files: readonly string[]): string {
  const tree = buildTree(files);
  return [
    "// Generated by scripts/generate-routes.ts. Do not edit.",
    'import { Outlet, type RouteObject } from "react-router";',
    'import { BootFallback, GlobalRouteError } from "../shared/errors/global-error-boundary";',
    "",
    "export const routes: RouteObject[] = [",
    routeSource(tree, 2, true),
    "];",
    "",
  ].join("\n");
}

export function routeKind(file: string): RouteKind | null {
  return routeFile.exec(path.posix.basename(file))?.[1] as RouteKind | undefined ?? null;
}
