import { statfsSync } from "node:fs";
import { readFile } from "node:fs/promises";
import { contractDigest, object, parse } from "../customer-server/data.ts";
import { atLeast, origin } from "../customer-server/config.ts";
import { compatibility } from "../customer-server/release.ts";
const disk = statfsSync("/");
const minimumGb = Number(process.argv[5] ?? "10");
if (!Number.isSafeInteger(minimumGb) || minimumGb < 1 || disk.bavail * disk.bsize < minimumGb * 1024 ** 3) throw new Error("Insufficient free disk in the Docker image store");
const upstream = origin(process.argv[2] ?? "");
const shellFloor = process.argv[3] ?? "";
const policy = compatibility(parse(await readFile(process.argv[4] ?? "/repo/deploy/customer-server/release.json", "utf8")));
if (!atLeast(shellFloor, policy.minimumShellVersion)) throw new Error("Installed shell baseline is incompatible");
const response = await fetch(`${upstream}/api/v1/user/authenticated`, { redirect: "error", signal: AbortSignal.timeout(15_000) });
if (![200,401,403].includes(response.status)) throw new Error("Existing backend API is unreachable");
await response.body?.cancel();
const contract = await fetch(`${upstream}/swagger/v1/swagger.json`, { redirect: "error", signal: AbortSignal.timeout(15_000) });
if (!contract.ok) throw new Error("Backend OpenAPI contract is unavailable");
const bytes = await contract.text();
if (bytes.length > 32 * 1024 * 1024) throw new Error("Backend contract exceeds verification limit");
const value = object(parse(bytes));
if (!value.paths || typeof value.openapi !== "string" || !policy.backendContracts.includes(contractDigest(value))) throw new Error("Backend contract is not approved for this frontend");
console.log("API connectivity, backend contract and installed-shell baseline verified");
